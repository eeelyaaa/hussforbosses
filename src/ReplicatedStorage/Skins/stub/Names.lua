local function byIndex(prefix: string, n: number): { string }
	local t = {}
	for i = 1, n do
		t[i] = prefix .. i
	end
	return t
end
local function byKey(keys: { string }): { [string]: string }
	local t = {}
	for _, k in ipairs(keys) do
		t[k] = k
	end
	return t
end
